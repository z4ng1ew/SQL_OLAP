## ТАБЛИЦА СИМВОЛОВ ФОРМАТА:

| Символ | Значение | Пример |
|--------|----------|--------|
| **9** | Опциональная цифра (не показывай ноль в начале) | 99 → `12` или ` 5` |
| **0** | Обязательная цифра (показывай всегда) | 00 → `05` |
| **.** | Десятичная точка | 99.99 → `12.34` |
| **,** | Разделитель тысяч | 9,999 → `1,234` |
| **FM** | Убрать пробелы и лишние нули | FM99 → `5` вместо ` 5` |
| **$** | Знак доллара | $999 → `$123` |
| **L** | Символ валюты (зависит от локали) | L999 → `₽123` |

