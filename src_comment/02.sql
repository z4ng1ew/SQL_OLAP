## РЕКОМЕНДАЦИЯ ДЛЯ ЗАЩИТЫ

**Используй TO_CHAR с FM** — это стандартный способ форматирования чисел в PostgreSQL.

Если спросят "а почему не просто ::NUMERIC?":
> "::NUMERIC оставляет все знаки после запятой, которые были при вычислении. TO_CHAR с форматом FM позволяет точно контролировать количество знаков и убрать незначащие нули."

Если спросят "что такое FM?":
> "Fill Mode — режим заполнения в PostgreSQL, который убирает лишние пробелы и незначащие нули при форматировании чисел."




























## РАЗБОР ФОРМАТА 'FM999999999999990.99'

Давай разберем **ПО ЧАСТЯМ**:

```
'FM999999999999990.99'
 ↓  ↓              ↓↓↓
 │  │              │││
 │  │              │└─ дробная часть
 │  │              └── точка (разделитель)
 │  └─────────────── целая часть
 └──────────────────── режим форматирования
```

---

## ЧАСТЬ 1: FM (Fill Mode)

**FM** = Fill Mode = "Режим заполнения"

Что делает:
- ✓ Убирает **лишние пробелы** слева
- ✓ Убирает **незначащие нули** справа

**БЕЗ FM:**
```sql
TO_CHAR(624, '999999999999990.99')    → '            624.00'
                                           ↑ пробелы слева
```

**С FM:**
```sql
TO_CHAR(624, 'FM999999999999990.99')  → '624.00'
                                           ↑ пробелов нет!
```

---

## ЧАСТЬ 2: 999999999999990 (целая часть)

Это **ШАБЛОН** для целой части числа (до точки).

### Что означают цифры?

**9** = "опциональная цифра" (если ноль в начале — не показывай)
**0** = "обязательная цифра" (показывай всегда, даже если ноль)

### Зачем так много девяток?

```
999999999999990
↑            ↑
│            └── последняя цифра ОБЯЗАТЕЛЬНАЯ (0)
└───────────── первые 14 позиций ОПЦИОНАЛЬНЫЕ (9)
```

Это означает: **"У числа может быть до 15 цифр в целой части"**

### Примеры:

| Число | Формат без FM | С FM | Объяснение |
|-------|---------------|------|------------|
| 5 | `             5` | `5` | 14 девяток пропущены, показан только 0 |
| 624 | `           624` | `624` | 12 девяток пропущены |
| 123456 | `        123456` | `123456` | 9 девяток пропущены |

**Последний ноль (0)** гарантирует, что хотя бы одна цифра будет показана:

```sql
TO_CHAR(0, 'FM999999999999990.99')  → '0.00'
                           ↑
                      эта цифра ОБЯЗАТЕЛЬНА
```

Без этого нуля:
```sql
TO_CHAR(0, 'FM99999999999999.99')   → '.00'  ← нет нуля!
```

