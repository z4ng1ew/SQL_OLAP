## ПОЧЕМУ ИМЕННО 999999999999990.99?

### Количество девяток (14 штук):

**999999999999990** = 15 позиций для целой части

Это позволяет форматировать числа до:
```
999,999,999,999,999 (почти квадриллион)
```

Для цен пицц это **избыточно**, но безопасно — точно хватит.

### Последний ноль:

**0** в конце гарантирует, что число 0 покажется как `0`, а не как пустота.

### Две девятки после точки:

**.99** = 2 знака после запятой (центы, копейки)

