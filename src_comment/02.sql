## ЧАСТЬ 3: . (точка)

Это просто **разделитель** между целой и дробной частью.

```
624.50
   ↑
   точка
```

---

## ЧАСТЬ 4: 99 (дробная часть)

Это **ШАБЛОН** для дробной части (после точки).

**99** = "две опциональные цифры после точки"

### Примеры:

| Число | Результат | Объяснение |
|-------|-----------|------------|
| 624 | 624.00 | Дробной части нет → добавляем .00 |
| 624.5 | 624.50 | Одна цифра → добавляем 0 справа |
| 624.75 | 624.75 | Две цифры → показываем как есть |

---

## ПОЛНЫЙ ПРИМЕР:

```sql
TO_CHAR(624, 'FM999999999999990.99')
        ↓         ↓              ↓↓
      число    целая часть   дробная часть
```

### Шаг за шагом:

**Шаг 1:** Число 624

**Шаг 2:** Применяем шаблон к целой части:
```
999999999999990
             624
↑          ↑
14 девяток  цифры числа
пропускаем
```
Результат: `624`

**Шаг 3:** Добавляем точку:
```
624.
```

**Шаг 4:** Применяем шаблон к дробной части:
```
99
00  ← дробной части нет, добавляем нули
```
Результат: `624.00`

**Шаг 5:** FM убирает лишние пробелы (но их и так нет)

**ИТОГО:** `624.00`

