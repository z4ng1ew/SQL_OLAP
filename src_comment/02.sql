## КОРОТКИЙ ОТВЕТ:

**'FM999999999999990.99'** читается так:

1. **FM** — убери лишние пробелы и нули
2. **999999999999990** — целая часть (до 15 цифр), последний 0 обязателен
3. **.** — точка-разделитель
4. **99** — дробная часть (2 цифры после точки)

**Каждая 9** = "если есть цифра — покажи, если нет — пропусти"
**Ноль 0** = "покажи обязательно, даже если это ноль"

**624** → `'624.00'`
**805.5** → `'805.50'`
**10** → `'10.00'`

