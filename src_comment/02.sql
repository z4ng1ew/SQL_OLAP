## АЛЬТЕРНАТИВНЫЕ ФОРМАТЫ:

### Короткий (для цен до 999,999):

```sql
TO_CHAR(624, 'FM9990.99')  → '624.00'
```

**9990.99** = максимум 4 цифры в целой части + 2 в дробной

### Без дробной части:

```sql
TO_CHAR(624.75, 'FM999999999999990')  → '625'  (округлит)
```

### С 4 знаками после точки:

```sql
TO_CHAR(624.1234, 'FM999999999999990.9999')  → '624.1234'
```

### С запятыми-разделителями:

```sql
TO_CHAR(1234567, 'FM999,999,999,990.99')  → '1,234,567.00'
```

**Запятая (,)** в формате означает разделитель тысяч.

