## Возможные вопросы на защите

**В: Почему нет GROUP BY?**
О: Потому что нам нужно **одно число** по всей таблице — глобальное среднее. `GROUP BY` разбил бы таблицу на группы (например, по имени пиццерии), и `AVG` считался бы для каждой группы отдельно. Без `GROUP BY` вся таблица — одна гигантская группа.

**В: Что будет, если rating содержит NULL?**
О: `AVG` **игнорирует** NULL. Пример:
```
Рейтинги: 4.5, NULL, 3.8, 3.2, NULL, 4.1
AVG = (4.5 + 3.8 + 3.2 + 4.1) / 4 = 3.9
```
Делится на 4 (количество не-NULL значений), а не на 6 (общее количество строк). Это поведение всех агрегатных функций в SQL: `SUM`, `AVG`, `MAX`, `MIN` — все пропускают NULL. Исключение — `COUNT(*)`, который считает ВСЕ строки.

**В: Зачем ROUND, если можно TRUNC?**
О: `ROUND` — **округляет** (3.91667 → 3.9167). `TRUNC` (truncate — усечение) — **обрезает** без округления (3.91667 → 3.9166). Задание требует округление, поэтому `ROUND`.

**В: Что если таблица pizzeria пуста?**
О: `AVG` от пустого множества = NULL. Результат: одна строка со значением `NULL` в столбце `global_rating`. `ROUND(NULL, 4)` тоже вернёт NULL — любая функция от NULL даёт NULL.

**В: Это самый короткий запрос в Day 07?**
О: Да. Две строки: `SELECT ... FROM`. Нет JOIN, нет GROUP BY, нет WHERE, нет ORDER BY. Просто одна агрегатная функция по всей таблице.

**В: Почему именно 4 знака после запятой?**
О: Так требует задание. Ожидаемый результат — `3.9167`. Если написать `ROUND(AVG(rating), 2)`, получим `3.92` — не совпадёт с эталоном при проверке.

**В: В чём разница между ROUND(x, 4) и ROUND(x)?**
О: `ROUND(x)` без второго аргумента округляет до **целого числа**: `ROUND(3.9167) = 4`. `ROUND(x, 4)` — до 4 знаков после запятой. Второй аргумент — количество десятичных разрядов (decimal places — десятичные позиции).

**В: Можно ли вместо AVG написать SUM/COUNT?**
О: Да, `AVG(rating)` математически эквивалентен `SUM(rating) / COUNT(rating)`. Но есть тонкость с типами — см. альтернативу ниже.

