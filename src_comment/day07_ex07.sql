## Альтернативные варианты

```sql
-- Вариант 1: явное приведение типа перед ROUND
SELECT
    ROUND(AVG(rating)::NUMERIC, 4) AS global_rating
FROM pizzeria;
-- ::NUMERIC — явный CAST (приведение типа) к типу NUMERIC.
-- В PostgreSQL AVG от float/real возвращает double precision,
-- а ROUND(double precision, int) может не существовать
-- в некоторых версиях — нужен NUMERIC.
-- С ::NUMERIC гарантированно работает.
-- В нашей базе rating уже numeric, так что результат тот же,
-- но это хорошая привычка.


-- Вариант 2: CAST вместо ::  (стандарт ANSI SQL)
SELECT
    ROUND(CAST(AVG(rating) AS NUMERIC), 4) AS global_rating
FROM pizzeria;
-- CAST(... AS NUMERIC) — стандартная запись ANSI SQL.
-- Делает то же самое, что ::NUMERIC.
-- ::NUMERIC — синтаксис только PostgreSQL (не переносим).
-- CAST — работает везде: Oracle, MySQL, MS SQL, PostgreSQL.


-- Вариант 3: SUM / COUNT вместо AVG (ручная формула)
SELECT
    ROUND(SUM(rating) / COUNT(rating), 4) AS global_rating
FROM pizzeria;
-- AVG(x) = SUM(x) / COUNT(x) — математически то же самое.
-- COUNT(rating) считает только NOT NULL строки — как и AVG.
--
-- НЮАНС: если rating — integer, то SUM/COUNT даст
-- целочисленное деление (отбросит дробную часть).
-- В нашей базе rating — numeric/float, поэтому проблемы нет.
-- Но для безопасности можно:
-- ROUND(SUM(rating) / COUNT(rating)::NUMERIC, 4)


-- Вариант 4: с защитой от пустой таблицы через COALESCE
SELECT
    COALESCE(ROUND(AVG(rating), 4), 0) AS global_rating
FROM pizzeria;
-- Если таблица пуста: AVG = NULL → ROUND = NULL → COALESCE → 0.
-- Вместо NULL вернёт 0.
-- В текущем задании не требуется, но на продакшене
-- (production — рабочая/боевая среда) — хорошая практика.


-- Вариант 5: подзапрос (избыточно, но демонстрирует подход)
SELECT
    ROUND(avg_rating, 4) AS global_rating
FROM (
    SELECT AVG(rating) AS avg_rating
    FROM pizzeria
) AS stats;
-- Внутренний подзапрос считает среднее,
-- внешний — округляет.
-- Разделение вычисления и форматирования.
-- Избыточно для одной функции, но полезный паттерн (шаблон),
-- когда вычислений много и хочется вынести их в подзапрос.


-- Вариант 6: с использованием оконной функции (полностью избыточно)
SELECT DISTINCT
    ROUND(AVG(rating) OVER (), 4) AS global_rating
FROM pizzeria;
-- AVG(rating) OVER () — оконная функция БЕЗ партиции.
-- OVER () = «по всей таблице» — аналог AVG без GROUP BY.
-- Без DISTINCT: вернёт одинаковое значение в каждой строке
-- (6 строк с одним и тем же числом 3.9167).
-- DISTINCT схлопнет до одной строки.
-- Совершенно избыточно, но показывает знание оконных функций.
```

Для задания **основной вариант** — идеален. На защите стоит упомянуть **вариант 1** (`::NUMERIC`) если спросят про типы данных, и **вариант 3** (`SUM/COUNT`) если спросят «а что такое AVG изнутри?».